public class CalcularMedia {
    public static void main(String[] args) {

        //calcular a média do valor
        double nota1 = 7.5;
        double nota2 = 8.0;
        double nota3 = 9.0;

        //encontrar o valor da média
        double valorMedia = (nota1+nota2+nota3)/3;
        System.out.println(valorMedia);
    }
}
